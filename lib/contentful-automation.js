export async function getPageAutomationDetail(id, preview) {
  const entries = await fetchGraphQL(
    `query {
        pageAutomations(id:"${id}",preview: ${preview ? 'true' : 'false'}) {
               ${POST_GRAPHQL_PAGE_AUTOMATION_DETAILS_FIELDS}
      }
    }`,
    preview
  );
  return entries?.data?.pageAutomations;
}
